import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const shared = readFileSync(join(root, 'lib/definition.js'), 'utf8').replace(/^export /gm, '');
const diagnosticContract = readFileSync(join(root, 'lib/diagnostics-contract.js'), 'utf8').replace(/^export /gm, '');
const template = `const team = ${readFileSync(join(root, 'examples/ur-team.json'), 'utf8')};\n`
  + readFileSync(join(root, 'lib/team-template.js'), 'utf8').replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const parts = ['logic', 'locales', 'styles', 'tools', 'inline', 'options', 'graph', 'anchored', 'card', 'instances', 'apply'];
const body = parts.map(part => readFileSync(join(root, 'src/client', `${part}.js`), 'utf8')).join('\n');
const built = `// Generated by scripts/build-client.mjs. Edit lib/definition.js or src/client/*.js.
window.__ModuleLoader__.load({ id: '@mimo-codex/dsh-subagentbook', factory(require) {
const react = require('react');
const h = react.createElement;
${shared}
${diagnosticContract}
${template}
${body}
return { apply, inject, parseBook, resolvePreset, hostedModels, resolvePrompt, resolveToolPrompt, createEditor, settingsWriter };
} });
`;
const target = join(root, 'lib/client.js');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== built) throw new Error('Stale lib/client.js: run npm run build:client');
  console.log('PASS client build is current');
} else { writeFileSync(target, built); console.log('Built single client entry with shared definition parser'); }
